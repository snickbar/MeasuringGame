// Writes anim/object-recency.js: for every picture in items/ the time it was last added or changed (git commit time, or now
// when it has uncommitted changes). The Object picker lists the newest / most recently updated objects first from this.
// Runs from sync-www. Without git history (a shallow checkout) it leaves the committed file alone.
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const ROOT = path.join(__dirname, '..'), OUT = path.join(ROOT, 'anim', 'object-recency.js');
function git(args) { return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] }); }
try {
  let old = {};
  try { old = JSON.parse(fs.readFileSync(OUT, 'utf8').match(/RECENCY = (\{[^\n]*\});/)[1]); } catch (e) { /* first run */ }
  const latest = {}; let stamp = 0;
  for (const line of git(['log', '--no-renames', '--name-only', '--format=@%ct', '--', 'items']).split('\n')) {
    if (line[0] === '@') stamp = Number(line.slice(1));
    else { const m = /^items\/([^/]+)\.webp$/.exec(line.trim()); if (m && !latest[m[1]]) latest[m[1]] = stamp; }
  }
  if (Object.keys(latest).length < 50) process.exit(0); // not enough history to say anything
  const now = Math.floor(Date.now() / 1000);
  for (const line of git(['status', '--porcelain', '--', 'items']).split('\n')) {
    const m = /items\/([^/]+)\.webp/.exec(line); if (m) latest[m[1]] = now;
  }
  const out = {};
  for (const id of Object.keys(latest).sort()) {
    const keep = old[id] != null && Math.abs(old[id] - latest[id]) <= 3600; // a commit a few minutes after the sync is the same change
    out[id] = keep ? old[id] : latest[id];
  }
  const text = '// Generated by scripts/build-object-recency.cjs (run by sync-www): when each object picture last changed (unix seconds).\nexport const RECENCY = ' + JSON.stringify(out) + ';\n';
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) fs.writeFileSync(OUT, text);
} catch (e) { console.warn('object recency not updated:', e.message); }
