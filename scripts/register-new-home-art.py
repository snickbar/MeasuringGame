"""Preserve generated alpha, convert to lossless WebP, measure atlas gutters.

This does not paint, remove backgrounds, crop, rescale, or reconstruct artwork.
The runtime selects independently drawn cells using the measured source bounds.
"""
from pathlib import Path
from itertools import groupby
import json
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'art-source/new-home-scenes'
OUT=ROOT/'anim/home-art'
COUNTS={'hero-make-believe':3,'books-make-believe':3,'gifts-holiday-mix':2}
def measure(im,count):
    alpha=im.getchannel('A')
    occupied=[alpha.crop((x,0,x+1,im.height)).getextrema()[1]>128 for x in range(im.width)]
    gaps=[];start=0
    for value,run in groupby(occupied):
        end=start+len(list(run))
        if not value and start>0 and end<im.width:gaps.append((start,end))
        start=end
    gaps=sorted(sorted(gaps,key=lambda g:g[1]-g[0],reverse=True)[:count-1])
    if len(gaps)!=count-1:raise ValueError('Missing atlas gutters')
    cuts=[0]+[(a+b)//2 for a,b in gaps]+[im.width];cells=[]
    for left,right in zip(cuts,cuts[1:]):
        box=alpha.crop((left,0,right,im.height)).point(lambda a:255 if a>128 else 0).getbbox()
        if not box:raise ValueError('Empty atlas cell')
        x,y,r,b=box;x=max(0,x-2);y=max(0,y-2);r=min(right-left,r+2);b=min(im.height,b+2)
        cells.append([left+x,y,r-x,b-y])
    return cells
sprites={}
for path in sorted(SOURCE.glob('*.png')):
    im=Image.open(path).convert('RGBA');name=path.stem
    if name.startswith('home-'):continue
    im.save(OUT/(name+'.webp'),lossless=True,method=6)
    if not name.startswith('plate-'):
        if im.getchannel('A').getextrema()[0]!=0:raise ValueError('Missing transparent alpha: '+name)
        sprites[name]={'file':name+'.webp','w':im.width,'h':im.height,'cells':measure(im,COUNTS.get(name,1))}
art={}
for scene,hero,prop,bounds in [
 ('make-believe','hero-make-believe','books-make-believe',[[15,690,370,460],[380,605,270,550]]),
 ('holiday-mix','hero-holiday-mix','gifts-holiday-mix',[[40,565,365,590],[410,449,190,706]])]:
    entry={'plate':{'file':'plate-'+scene+'.webp'},'critters':[]}
    for role,name,box in zip(['hero','hero2'],[hero,prop],bounds):
        x,y,w,h=box
        entry[role]={'file':name+'.webp','x':0,'y':0,'w':100,'sw':704,'sh':1520,'ab':{'x':x,'y':y,'width':w,'height':h},'ox':(x+w/2)/704*100,'oy':(y+h)/1520*100}
    critter=sprites['critter-'+scene+'-a'];x,y,w,h=critter['cells'][0]
    entry['critters'].append({'file':critter['file'],'w':critter['w'],'h':critter['h'],'ab':{'x':x,'y':y,'width':w,'height':h}})
    art[scene]=entry
(ROOT/'anim/home-new-art.mjs').write_text('// Generated by scripts/register-new-home-art.py.\nexport const NEW_HOME_ART = '+json.dumps(art,indent=1)+';\nexport const NEW_HOME_SPRITES = '+json.dumps(sprites,indent=1)+';\n')
(SOURCE/'runtime-layout.json').write_text(json.dumps(art,indent=1)+'\n')
print(json.dumps(sprites,indent=1))
