// Turns anim/home-art/manifest.json into anim/home-art-layout.mjs: where each foreground layer sits in the 704 x 1520
// Home picture, so the game never has to fetch the (large) manifest at runtime. Run: node scripts/build-home-art-layout.cjs
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..'),man=JSON.parse(fs.readFileSync(path.join(root,'anim/home-art/manifest.json'),'utf8'));
const REF_W=704,REF_H=1520,r=(n,d=3)=>Number(n.toFixed(d));
const out={};
for(const a of man.assets){
  if(!a.scene||['clouds.png','sparkles.png','coin-spin.png'].includes(a.name))continue; // shared sheets are described in shared-sprites.json
  const s=out[a.scene]??={plate:null,hero:null,hero2:null,critters:[]};
  if(a.plate){s.plate={file:a.name};continue;}
  if(/^critter-/.test(a.name)){s.critters.push({file:a.name,w:a.width,h:a.height,ab:a.alphaBounds});continue;}
  const t=a.targetBoundsInReference,ab=a.alphaBounds;
  // Fit the visible part of the sprite inside the original object's box (keeping its shape), bottom-centred.
  const k=Math.min(t.width/ab.width,t.height/ab.height);
  const left=t.x+t.width/2-(ab.x+ab.width/2)*k,top=t.y+t.height-(ab.y+ab.height)*k;
  s[a.name.startsWith('hero2')?'hero2':'hero']={file:a.name,
    x:r(left/REF_W*100),y:r(top/REF_H*100),w:r(a.width*k/REF_W*100),
    ox:r((ab.x+ab.width/2)/a.width*100,2),oy:r((ab.y+ab.height)/a.height*100,2)};
}
fs.writeFileSync(path.join(root,'anim/home-art-layout.mjs'),'// Generated by scripts/build-home-art-layout.cjs - do not edit by hand.\nexport const HOME_ART_REF = { width: 704, height: 1520 };\nexport const HOME_ART = '+JSON.stringify(out,null,1)+';\n');
console.log(Object.keys(out).length+' scenes');
