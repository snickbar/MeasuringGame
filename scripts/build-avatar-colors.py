"""Builds the data the phone needs to recolor avatars (Avatar Level 4: Colors).

  python scripts/build-avatar-colors.py

Writes
  anim/avatar-colors-data.mjs      for every avatar: its recolor layers ("h19" = hue shift around 19 degrees, ...) and the colours it offers
  anim/avatar-color-masks.png      one small picture holding every avatar's layer masks (red = layer 1, green = layer 2)
The phone paints a colour by shifting the pixels the masks point at (anim/avatar-colors.mjs), so no extra avatar pictures ship.
The rules that decide which pixels count live in scripts/avatar-colors/rules.py. Needs Pillow, numpy and scipy (developer tool only).
"""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "avatar-colors"))
import numpy as np
from PIL import Image
import rules

ROOT = rules.ROOT
CELL, COLS = 120, 18
REC = []
KIND = {"hue": "h", "hueb": "b", "flat": "f", "tint:white": "w", "tint:gray": "g", "tint:black": "k", "tint:cream": "c", "tint:gray2": "G", "tint8": "t", "fill": "F"}
TARGETS = {"P": ("Pink", 330), "B": ("Blue", 215), "G": ("Green", 130), "U": ("Purple", 280), "Y": ("Yellow", 50), "R": ("Red", 0), "T": ("Teal", 175)}
ORDER = "PBGUYRT"

def hook(a, c, kind, m, target):
    if m.sum() < 20: return
    cen = None
    if kind in ("hue", "hueb"):
        ang = np.deg2rad(c.h[m]); cen = float(np.rad2deg(np.arctan2(np.sin(ang).mean(), np.cos(ang).mean())) % 360)
    elif kind == "flat":
        ang = np.deg2rad(c.h[m]); cen = float(np.rad2deg(np.arctan2(np.sin(ang).mean(), np.cos(ang).mean())) % 360)
    REC.append((kind, m.copy(), cen))
rules.apply = hook
rules.apply_fill = lambda out, c, hole, target: REC.append(("fill", hole.copy(), None))

def layers_rc2(im, n):
    mode, f = rules.cfg(n)
    a = np.array(im).astype(float) / 255; h, s, v = rules.hsv(a); H = a.shape[0]
    Y = np.broadcast_to(np.arange(H)[:, None], h.shape)
    m = (a[..., 3] > .5) & f(h, s, v, Y, H)
    if m.sum() < 20: return []
    cen = None
    if mode == "hue":
        ang = np.deg2rad(h[m]); cen = float(np.rad2deg(np.arctan2(np.sin(ang).mean(), np.cos(ang).mean())) % 360)
    return [({"hue": "hue", "tint": "tint8", "flat": "flat"}[mode], m, cen)]

def layers_for(n):
    name = f"av{n:02d}" if n < 100 else f"av{n}"
    im = rules.load(name)
    REC.clear()
    if n in rules.S: rules.shift(im, n, 330)
    elif rules.cfg(n): return layers_rc2(im, n)
    else: rules.auto2(im, 330)
    return list(REC)

def cd(a, b):
    d = abs(a - b) % 360
    return min(d, 360 - d)

def main():
    ids = sorted(int(f[2:-5]) for f in os.listdir(os.path.join(ROOT, "avatars")) if f.endswith(".webp"))
    # Colours that were approved on the review page (the original plus four) for the two avatars the simple rule would have given a different set.
    approved = {11: "PGUT", 112: "PGUT"}
    sheet = np.zeros(((len(ids) + COLS - 1) // COLS * CELL, COLS * CELL, 3), np.uint8)
    out = []
    for i, n in enumerate(ids):
        L = layers_for(n)
        assert 1 <= len(L) <= 2, (n, len(L))
        r0, c0 = divmod(i, COLS)
        for k, (_, m, _) in enumerate(L):
            cell = np.zeros((CELL, CELL), np.uint8); h, w = m.shape; cell[:h, :w] = m * 255
            sheet[r0 * CELL:(r0 + 1) * CELL, c0 * CELL:(c0 + 1) * CELL, k] = cell
        first = next((cen for kind, _, cen in L if cen is not None), None)
        shades = approved.get(n) or "".join(t for t in ORDER if first is None or cd(TARGETS[t][1], first) >= 35)[:4]
        name = f"av{n:02d}" if n < 100 else f"av{n}"
        out.append((name, ",".join(KIND[k] + ("" if c is None else str(round(c))) for k, _, c in L) + "|" + shades))
    Image.fromarray(sheet, "RGB").save(os.path.join(ROOT, "anim", "avatar-color-masks.png"), optimize=True)
    lines = ['// Generated by scripts/build-avatar-colors.py - do not edit.', '// avatar: "layers|colours". A layer is a kind letter (h/b hue, f flat, w/g/k/c/G tint, t tint2, F fill) and, for hue kinds, the', '// middle hue of the painted area. Colours are letters in the order they are offered (P Pink, B Blue, G Green, U Purple, Y Yellow, R Red, T Teal).',
             f"export const COLOR_MASK_CELL = {CELL}, COLOR_MASK_COLS = {COLS};", "export const AVATAR_COLOR_DATA = {"]
    lines += [f'  {n}: "{v}",' for n, v in out]
    lines.append("};")
    open(os.path.join(ROOT, "anim", "avatar-colors-data.mjs"), "w").write("\n".join(lines) + "\n")
    print(len(out), "avatars;", os.path.getsize(os.path.join(ROOT, "anim", "avatar-color-masks.png")) // 1024, "KB masks;", os.path.getsize(os.path.join(ROOT, "anim", "avatar-colors-data.mjs")) // 1024, "KB data")

if __name__ == "__main__": main()
