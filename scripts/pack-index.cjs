// The page that ships is not byte for byte the page in the repository: its big inline module (the game, about 1.2 MB) is moved
// into a file of its own, app.mjs. The repository keeps it inline, because that is where it is edited and where the checks read it.
//
// Why: an inline module is part of the HTML, so the browser's main thread has to read all of it as page text and then compile it,
// before anything can run. A separate file is fetched, parsed and compiled by the browser away from the main thread. Measured with
// the page loading at 4x CPU slowdown (a slow phone): Home appears about 14% sooner (2.0 s -> 1.7 s), the main thread is blocked
// about 25% less while loading, and the HTML itself is 56% smaller (2.2 MB -> 0.96 MB).
//
// The module itself is not changed by a single byte, only moved. Its imports are relative ("./anim/...") and resolve the same from
// app.mjs, which sits next to index.html. app.mjs starts with enough blank lines that its line numbers are index.html's, so a
// stack trace or a debugger points at the same line of the repository's index.html.
//
// Works on strings; callers read and write the files as 'latin1' so every byte survives unchanged.
const FILE = 'app.mjs';
const OPEN = '<script type="module">';
const CLOSE = '</script>';
const TAG = `<script type="module" src="${FILE}"></script>`;
const HEADER = '// Generated by scripts/pack-index.cjs from the inline module in index.html, which is where to edit it. Line numbers match index.html.';

// Returns { html, appModule } for a page with exactly one inline module, or null when the page is not built that way (the caller
// then ships the page unchanged, which is slower to load but works).
function splitIndex(html) {
  const open = html.indexOf(OPEN);
  if (open < 0 || html.indexOf(OPEN, open + OPEN.length) >= 0) return null;
  // Any other inline module, even with attributes, means this is not the shape that was measured and checked.
  const inline = [...html.matchAll(/<script\b[^>]*\btype\s*=\s*["']?module["']?[^>]*>/gi)].filter(m => !/\bsrc\s*=/i.test(m[0]));
  if (inline.length !== 1) return null;
  if (html.includes(`src="${FILE}"`) || html.includes(`src='${FILE}'`)) return null;
  const start = open + OPEN.length;
  const close = html.indexOf(CLOSE, start);
  if (close < 0) return null;
  const code = html.slice(start, close);
  if (!code.trim()) return null;
  const line = html.slice(0, open).split('\n').length; // the line of index.html the module starts on, counting from 1
  return {
    html: html.slice(0, open) + TAG + html.slice(close + CLOSE.length),
    appModule: line > 1 ? HEADER + '\n'.repeat(line - 1) + code : code,
  };
}

// The inverse: put the module back where the tag is. (Slices, not String.replace, which would read the $ in the code as patterns.)
function unsplitIndex(html, appModule) {
  const at = html.indexOf(TAG);
  if (at < 0 || html.indexOf(TAG, at + 1) >= 0) throw Error('The packaged index.html does not have exactly one ' + TAG);
  const line = html.slice(0, at).split('\n').length;
  const prefix = line > 1 ? HEADER + '\n'.repeat(line - 1) : '';
  if (!appModule.startsWith(prefix)) throw Error(FILE + ' does not start with its header and the blank lines that keep line numbers');
  return html.slice(0, at) + OPEN + appModule.slice(prefix.length) + CLOSE + html.slice(at + TAG.length);
}

// The packed page and app.mjs together are exactly the repository page: putting the module back gives the original, byte for byte.
// Throws a message naming what differs. Used by the build and by the checks that run before anything is published.
function assertPacked(source, packedHtml, appModule) {
  const again = splitIndex(source);
  if (!again) throw Error('index.html no longer has the single inline module that is moved to ' + FILE);
  if (packedHtml !== again.html) throw Error('The packaged index.html is not the repository index.html with its inline module replaced by ' + TAG);
  if (appModule !== again.appModule) throw Error(FILE + ' is not the repository index.html inline module');
  if (unsplitIndex(packedHtml, appModule) !== source) throw Error('Putting ' + FILE + ' back into the packaged index.html does not give the repository index.html');
  return true;
}

module.exports = { FILE, TAG, splitIndex, unsplitIndex, assertPacked };
