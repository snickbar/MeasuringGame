"""Lossless format conversion + read-only alpha bounds for generated art sheets.

No drawing, matte removal or image reconstruction: the generated PNG alpha is
preserved. Runtime CSS selects each independent cell using its measured bounds.
"""
from pathlib import Path
from itertools import groupby
import json
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'art-source/home-refinements'
OUT=ROOT/'anim/home-art/refined'
IDS=['mugs','cones','blocks','cherry','ducks','ice','bowls','coins']

def bounds(alpha, box):
    b=alpha.crop(box).point(lambda a:255 if a>128 else 0).getbbox()
    if not b: raise ValueError('Empty sprite cell')
    x,y,r,bottom=b
    # Retain a two-pixel antialiasing margin inside the cell.
    x=max(0,x-2);y=max(0,y-2);r=min(box[2]-box[0],r+2);bottom=min(box[3]-box[1],bottom+2)
    return [x+box[0],y+box[1],r-x,bottom-y]

if __name__=='__main__':
    OUT.mkdir(exist_ok=True)
    result={}
    for id in IDS:
        im=Image.open(SOURCE/f'layers-{id}.png').convert('RGBA');a=im.getchannel('A')
        # The generator may use unequal cell widths. Measure the empty gutter.
        occupied=[a.crop((x,0,x+1,im.height)).getextrema()[1]>128 for x in range(im.width)]
        runs=[];start=0
        for value,group in groupby(occupied):
            n=len(list(group));end=start+n
            if not value and start>im.width*.2 and end<im.width*.9:runs.append((start,end))
            start=end
        if not runs:raise ValueError(f'No transparent gutter in {id}')
        left,right=max(runs,key=lambda r:r[1]-r[0]);split=(left+right)//2
        result[id]={'file':f'refined/layers-{id}.webp','base':bounds(a,(0,0,split,im.height)),'top':bounds(a,(split,0,im.width,im.height))}
        im.save(OUT/f'layers-{id}.webp','WEBP',lossless=True,method=6)
        print(id,result[id])
    for id in ['kibble','robot-palm']:
        Image.open(SOURCE/f'layers-{id}.png').save(OUT/f'{id}.webp','WEBP',lossless=True,method=6)
    (ROOT/'anim/home-layer-sheets.mjs').write_text('// Generated by scripts/register-home-layers.py.\nexport const HOME_LAYER_SHEETS = '+json.dumps(result,indent=2)+';\n',encoding='utf-8')
