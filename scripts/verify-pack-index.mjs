// The shipped page has its big inline module moved into app.mjs (scripts/pack-index.cjs says why). This checks the move: that it
// changes nothing but where the module lives, that the real index.html can still be split, and that the host will not serve a
// stale app.mjs next to a new index.html.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { FILE, TAG, splitIndex, unsplitIndex, assertPacked } = require('./pack-index.cjs');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// A small page shaped like index.html: a head, some markup, classic scripts, then one inline module. The code has what trips up
// text replacement: $& and $1 (String.replace reads those as patterns), template literals, a "</" string and non-ASCII text.
const code = '\n  import { a } from "./anim/a.mjs";\n  const price = `${a}$&$1$$`; const close = "</" + "div>";\n  const label = "café → été";\n  document.title = price + close + label;\n';
const page = line => ['<!DOCTYPE html>', '<html><head><title>x</title>', '<script>window.early = 1;</script></head><body>', '<p>hello</p>',
  '<script type="module" src="anim/home-fx.mjs"></script>', '<script src="monthly/motion.js"></script>', `<script type="module">${code}</script>`, '</body></html>'].join(line);

for (const eol of ['\n', '\r\n']) {
  const source = page(eol);
  const packed = splitIndex(source);
  assert(packed, 'A page with one inline module can be split');
  assert.equal(packed.html.split(TAG).length, 2, 'The packaged page has exactly one tag for the module');
  assert(!packed.html.includes('import { a }'), 'The code is no longer in the packaged page');
  assert(packed.html.includes('<script type="module" src="anim/home-fx.mjs"></script>') && packed.html.includes('<script src="monthly/motion.js"></script>'), 'The other scripts stay as they were');
  assert(packed.html.indexOf('home-fx.mjs') < packed.html.indexOf(TAG) && packed.html.indexOf('motion.js') < packed.html.indexOf(TAG), 'The module keeps its place after the scripts before it');
  assert.equal(unsplitIndex(packed.html, packed.appModule), source, 'Putting the module back gives the original page exactly');
  assert.equal(assertPacked(source, packed.html, packed.appModule), true);
  // Line numbers: a line of the module is on the same line number in app.mjs as in the page.
  const sourceLines = source.split('\n'), moduleLines = packed.appModule.split('\n');
  const start = sourceLines.findIndex(l => l.includes('<script type="module">'));
  for (let i = start + 1; i < start + 5; i++) assert.equal(moduleLines[i].replace(/\r$/, ''), sourceLines[i].replace(/\r$/, ''), 'Line ' + (i + 1) + ' is the same in app.mjs');
  assert.equal(moduleLines[0].startsWith('// Generated by scripts/pack-index.cjs'), true, 'app.mjs says where it comes from');
  assert.throws(() => assertPacked(source, packed.html, packed.appModule + 'x'), /app\.mjs is not/, 'A changed app.mjs is caught');
  assert.throws(() => assertPacked(source, packed.html.replace('hello', 'bye'), packed.appModule), /not the repository index\.html/, 'A changed page is caught');
}

// Pages that are not built that way are left alone (the build then ships them unchanged).
assert.equal(splitIndex('<html><body><p>no module</p></body></html>'), null, 'No inline module: nothing to move');
assert.equal(splitIndex('<body><script type="module" src="a.mjs"></script></body>'), null, 'A module that already has a file: nothing to move');
assert.equal(splitIndex('<body><script type="module">let a;</script><script type="module">let b;</script></body>'), null, 'Two inline modules: not the measured shape');
assert.equal(splitIndex('<body><script type="module" id="x">let a;</script></body>'), null, 'A module with attributes is not the measured shape');
assert.equal(splitIndex('<body><script type="module">   </script></body>'), null, 'An empty module: nothing to move');
assert.equal(splitIndex(`<body><script src="${FILE}"></script><script type="module">let a;</script></body>`), null, 'A page that already names app.mjs is left alone');
assert.equal(splitIndex('<script type="module">let first;</script>').appModule, 'let first;', 'A module on the first line needs no blank lines');

// The real page.
const source = fs.readFileSync(path.join(root, 'index.html'), 'latin1');
const real = splitIndex(source);
assert(real, 'index.html has exactly one inline module, so it can ship as ' + FILE + '. Without that, the page loads about 14% slower on a slow phone: see scripts/pack-index.cjs');
assert.equal(assertPacked(source, real.html, real.appModule), true);
assert(real.appModule.length > 500000, FILE + ' holds the game');
assert(real.html.length < source.length / 2, 'The packaged page is less than half the size');
for (const m of real.html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)) {
  assert(m[2].length < 100000, 'No large inline script is left in the packaged page: ' + m[1].trim().slice(0, 60) + ' has ' + m[2].length + ' bytes');
}
// The module's imports are relative to index.html; app.mjs sits next to it, so they mean the same files.
const imports = [...real.appModule.matchAll(/(?:from\s*|import\s*\(\s*)["'](\.{1,2}\/[^"']+)["']/g)].map(m => m[1]);
assert(imports.length > 50, 'The module has its relative imports');
assert(imports.every(i => i.startsWith('./anim/') || i.startsWith('./monthly/') || i.startsWith('./')), 'Relative imports stay within the folder the page is in');
for (const i of new Set(imports)) assert(fs.existsSync(path.join(root, i.split('?')[0])), 'Imported file exists: ' + i);
assert(!/\bimport\.meta\b/.test(real.appModule), 'The module does not use import.meta.url, which would differ between an inline module and app.mjs');

// The host revalidates app.mjs on every load, so a new index.html never runs with an old game module.
const firebase = JSON.parse(fs.readFileSync(path.join(root, 'firebase.json'), 'utf8'));
const rule = firebase.hosting.headers.find(h => h.source === '/' + FILE);
assert(rule && rule.headers.some(h => h.key === 'Cache-Control' && h.value === 'no-cache'), '/' + FILE + ' must be served with Cache-Control: no-cache in firebase.json');

// The builds use it.
assert(/splitIndex/.test(fs.readFileSync(path.join(root, 'scripts/sync-www.js'), 'utf8')), 'sync-www.js packs the page');

console.log(`Packed page: the game module moves to ${FILE} without changing a byte (CRLF too), the real index.html splits (${(source.length / 1048576).toFixed(2)} MB -> ${(real.html.length / 1048576).toFixed(2)} MB + ${(real.appModule.length / 1048576).toFixed(2)} MB), and the host revalidates it.`);
